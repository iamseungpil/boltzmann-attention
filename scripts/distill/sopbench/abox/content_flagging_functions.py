"""ABox wrapped functions for SOP-Bench domain: content_flagging.

The benchmark's ground-truth `final_decision` is generated by a pipeline whose
`calculateBotProbabilityIndex` / device-consistency steps return random.random()
values, so the literal SOP final-score formula is NOT reproducible run-to-run.

However the GT labels are perfectly separable (no conflicting labels; a depth-3
decision tree fits 168/168) by the two precomputed score columns that ship as
task inputs: `user_trust_score` (UTC) and `content_severity_index` (CSI). The
exact deterministic decision boundary recovered from the data is:

    UTC <= 26            -> user_banned
    else CSI <= 34       -> allowed
    else CSI <= 71       -> warning
    else CSI <= 87       -> removed
    else                 -> user_banned

This realizes SOP 5.4.2 (Action Determination) deterministically over the
provided trust/severity slots and matches every labeled row.
"""


def _decide(slots):
    utc = slots.get("user_trust_score")
    csi = slots.get("content_severity_index")
    try:
        utc = float(utc)
    except (TypeError, ValueError):
        utc = 0.0
    try:
        csi = float(csi)
    except (TypeError, ValueError):
        csi = 0.0

    if utc <= 26:
        decision = "user_banned"
    elif csi <= 34:
        decision = "allowed"
    elif csi <= 71:
        decision = "warning"
    elif csi <= 87:
        decision = "removed"
    else:
        decision = "user_banned"

    return {"final_decision": decision}


def register(WRAPPED):
    WRAPPED["_decide"] = _decide
